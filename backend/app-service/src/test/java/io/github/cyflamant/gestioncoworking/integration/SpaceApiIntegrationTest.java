package io.github.cyflamant.gestioncoworking.integration;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.security.test.context.support.WithMockUser;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

@SpringBootTest
@AutoConfigureMockMvc
@Transactional // each test is rolled back, so the DB stays clean
@WithMockUser(roles = "ADMIN") // independent of app.placeholder-user-role
class SpaceApiIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Test
    void createdSpaceCanBeReadBack() throws Exception {
        // Act 1: create a space through the API
        String body = mockMvc.perform(post("/api/spaces")
                .contentType(MediaType.APPLICATION_JSON)
                .content("""
                        { "name": "Salle intégration", "type": "ROOM",
                          "hourRate": 15.00, "halfDayRate": 50.00,
                          "dayRate": 90.00, "monthRate": 1500.00 }
                        """))
                .andExpect(status().isCreated())
                .andReturn().getResponse().getContentAsString();

        Integer id = JsonPath.read(body, "$.id"); // the id generated by MariaDB

        // Act 2 + Assert: read it back through the API
        mockMvc.perform(get("/api/spaces/" + id))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Salle intégration"))
                .andExpect(jsonPath("$.type").value("ROOM"))
                .andExpect(jsonPath("$.monthRate").value(1500.0));
    }

}
